#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
enum CellState {
    /// No summary and no scene: a frontier question.
    Empty,
    /// A summary but no scene yet.
    Planned,
    /// Scenes cover it.
    Covered,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize)]
struct CellCounts {
    empty: usize,
    planned: usize,
    covered: usize,
}

#[derive(Serialize)]
struct Cell {
    stage: Stage,
    state: CellState,
    summary: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    confidence: Option<Confidence>,
    scenes: Vec<String>,
}

#[derive(Serialize)]
struct ThreadRow {
    id: String,
    name: String,
    kind: ThreadKind,
    cells: Vec<Cell>,
}

#[derive(Serialize)]
struct ArcGrid {
    id: String,
    name: String,
    status: ArcStatus,
    /// False for shelved subplots: they are kept for later, not gaps.
    counted: bool,
    threads: Vec<ThreadRow>,
}

#[derive(Serialize)]
struct GridOut {
    /// Cell states across every counted arc.
    totals: CellCounts,
    arcs: Vec<ArcGrid>,
    /// Threads whose arc doesn't exist; shown so nothing hides, never counted.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    unattached: Vec<ThreadRow>,
}

fn grid(spec: &Spec, lookup: &Lookup) -> GridOut {
    // Scenes per (thread, stage), in reading order.
    let mut covering: HashMap<(&str, Stage), Vec<&str>> = HashMap::new();
    for (node, scene) in scene_nodes(spec) {
        if let Some(Coverage { thread, stage }) = &scene.coverage {
            covering
                .entry((thread.as_str(), *stage))
                .or_default()
                .push(node.id.as_str());
        }
    }
    for list in covering.values_mut() {
        list.sort_by_key(|id| lookup.order_key(id));
    }

    let row = |node: &Node, totals: Option<&mut CellCounts>| -> Option<ThreadRow> {
        let NodeBody::Thread(t) = &node.body else {
            return None;
        };
        let mut counts = CellCounts::default();
        let cells = t
            .stages
            .iter()
            .map(|entry| {
                let scenes: Vec<String> = covering
                    .get(&(node.id.as_str(), entry.stage))
                    .map(|v| v.iter().map(|s| s.to_string()).collect())
                    .unwrap_or_default();
                let summary = entry.summary.clone().filter(|s| !s.trim().is_empty());
                let state = if !scenes.is_empty() {
                    counts.covered += 1;
                    CellState::Covered
                } else if summary.is_some() {
                    counts.planned += 1;
                    CellState::Planned
                } else {
                    counts.empty += 1;
                    CellState::Empty
                };
                Cell {
                    stage: entry.stage,
                    state,
                    summary,
                    confidence: entry.confidence,
                    scenes,
                }
            })
            .collect();
        if let Some(totals) = totals {
            totals.empty += counts.empty;
            totals.planned += counts.planned;
            totals.covered += counts.covered;
        }
        Some(ThreadRow {
            id: node.id.clone(),
            name: node.name.clone(),
            kind: t.kind,
            cells,
        })
    };

    let mut totals = CellCounts::default();
    let mut placed: HashSet<&str> = HashSet::new();
    let mut arcs = Vec::new();
    for node in &spec.nodes {
        let NodeBody::Arc(arc) = &node.body else {
            continue;
        };
        let counted = arc.status != ArcStatus::Shelved;
        // The arc's own order first, then threads that name this arc but
        // aren't in its list.
        let mut thread_ids: Vec<&str> = arc.threads.iter().map(String::as_str).collect();
        let mut extra: Vec<&str> = lookup
            .thread_arc
            .iter()
            .filter(|(t, a)| **a == node.id && !thread_ids.contains(t))
            .map(|(t, _)| *t)
            .collect();
        extra.sort_unstable();
        thread_ids.extend(extra);
        let threads = thread_ids
            .into_iter()
            .filter_map(|id| spec.node(id))
            .filter_map(|t| {
                placed.insert(t.id.as_str());
                row(t, counted.then_some(&mut totals))
            })
            .collect();
        arcs.push(ArcGrid {
            id: node.id.clone(),
            name: node.name.clone(),
            status: arc.status,
            counted,
            threads,
        });
    }
    let unattached = spec
        .nodes
        .iter()
        .filter(|n| n.node_type() == NodeType::Thread && !placed.contains(n.id.as_str()))
        .filter_map(|n| row(n, None))
        .collect();
    GridOut {
        totals,
        arcs,
        unattached,
    }
}

