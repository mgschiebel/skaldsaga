#[derive(Serialize)]
struct RegisteredOut<'a> {
    #[serde(flatten)]
    def: &'a AttributeDef,
    source: Source,
}

#[derive(Serialize)]
struct InUse {
    registered: bool,
    /// Where the key is defined (the starter list or `spec/attributes.md`).
    #[serde(skip_serializing_if = "Option::is_none")]
    source: Option<Source>,
    #[serde(skip_serializing_if = "Option::is_none")]
    relation: Option<Relation>,
    /// For the inverse side of a pair (`child_of`), the registered key (`parent_of`).
    #[serde(skip_serializing_if = "Option::is_none")]
    pair_of: Option<String>,
    /// The uniqueness rule for this node type; `null` when there is none.
    cardinality: Option<Cardinality>,
    facts: Vec<String>,
}

#[derive(Serialize)]
struct AttributesOut<'a> {
    registered: Vec<RegisteredOut<'a>>,
    in_use: BTreeMap<&'static str, BTreeMap<String, InUse>>,
}

fn attributes<'a>(spec: &Spec, registry: &'a Registry) -> AttributesOut<'a> {
    let registered = registry
        .defs()
        .map(|(def, source)| RegisteredOut { def, source })
        .collect();
    let mut in_use: BTreeMap<&'static str, BTreeMap<String, InUse>> = BTreeMap::new();
    for node in &spec.nodes {
        let node_type = node.node_type();
        for fact in &node.facts {
            let Some(key) = &fact.attribute else { continue };
            let entry = in_use
                .entry(node_type.as_str())
                .or_default()
                .entry(key.clone())
                .or_insert_with(|| match registry.lookup(key) {
                    Some(found) => InUse {
                        registered: true,
                        source: Some(found.source),
                        relation: Some(found.def.relation),
                        pair_of: found.is_inverse_side.then(|| found.def.key.clone()),
                        cardinality: found.def.cardinality.for_type(node_type),
                        facts: Vec::new(),
                    },
                    None => InUse {
                        registered: false,
                        source: None,
                        relation: None,
                        pair_of: None,
                        cardinality: None,
                        facts: Vec::new(),
                    },
                });
            entry.facts.push(fact.id.clone());
        }
    }
    for keys in in_use.values_mut() {
        for entry in keys.values_mut() {
            entry.facts.sort();
        }
    }
    AttributesOut { registered, in_use }
}

