// Lookups shared by the views

struct Lookup<'a> {
    /// Fact ID to the ID of the node that holds it.
    fact_home: HashMap<&'a str, &'a str>,
    /// Scene ID to its place in the reading order.
    position: HashMap<&'a str, usize>,
    /// Thread ID to the arc it belongs to (from the thread's `arc` field or
    /// the arc's `threads` list).
    thread_arc: HashMap<&'a str, &'a str>,
}

impl<'a> Lookup<'a> {
    fn new(spec: &'a Spec) -> Self {
        let mut fact_home = HashMap::new();
        let mut thread_arc = HashMap::new();
        for node in &spec.nodes {
            for fact in &node.facts {
                fact_home.insert(fact.id.as_str(), node.id.as_str());
            }
            match &node.body {
                NodeBody::Thread(t) => {
                    thread_arc.entry(node.id.as_str()).or_insert(t.arc.as_str());
                }
                NodeBody::Arc(a) => {
                    for t in &a.threads {
                        thread_arc.insert(t.as_str(), node.id.as_str());
                    }
                }
                _ => {}
            }
        }
        let position = spec
            .sequence
            .iter()
            .enumerate()
            .map(|(i, id)| (id.as_str(), i))
            .collect();
        Lookup {
            fact_home,
            position,
            thread_arc,
        }
    }

    fn exists(&self, spec: &Spec, id: &str) -> bool {
        spec.node(id).is_some() || self.fact_home.contains_key(id)
    }

    /// Sort key that puts scenes in reading order, then the rest by ID.
    fn order_key<'b>(&self, id: &'b str) -> (usize, &'b str) {
        (self.position.get(id).copied().unwrap_or(usize::MAX), id)
    }
}

fn scene_nodes(spec: &Spec) -> impl Iterator<Item = (&Node, &crate::model::Scene)> {
    spec.nodes.iter().filter_map(|n| match &n.body {
        NodeBody::Scene(s) => Some((n, s)),
        _ => None,
    })
}

