/// Bumped when the shape of the index files changes.
pub const FORMAT: u32 = 1;

/// The index files, in the order they are written.
pub const FILES: [&str; 5] = [
    "backlinks.json",
    "attributes.json",
    "grid.json",
    "scenes.json",
    "status.json",
];

/// The `value` recorded for a shape decision answered with "keep it simple".
pub const NOT_EXPLORED: &str = "not_explored";

/// The five index files, as JSON.
#[derive(Debug, Clone, PartialEq)]
pub struct Index {
    pub backlinks: Value,
    pub attributes: Value,
    pub grid: Value,
    pub scenes: Value,
    pub status: Value,
}

impl Index {
    /// File name and contents, in [`FILES`] order.
    pub fn files(&self) -> [(&'static str, &Value); 5] {
        [
            (FILES[0], &self.backlinks),
            (FILES[1], &self.attributes),
            (FILES[2], &self.grid),
            (FILES[3], &self.scenes),
            (FILES[4], &self.status),
        ]
    }
}

/// What a rebuild did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rebuilt {
    /// Paths written, relative to the spec folder.
    pub files: Vec<String>,
    pub nodes: usize,
    pub problems: usize,
    pub broken_references: usize,
}

/// Loads the spec and rewrites every file in `spec/_index/`.
pub fn rebuild(project: &Project) -> Result<Rebuilt, FsError> {
    let spec_dir = project.spec_dir();
    let loaded = spec::load(&spec_dir)?;
    let index = build(&loaded);
    let dir = spec_dir.join(INDEX_DIR);
    let mut files = Vec::new();
    for (name, value) in index.files() {
        // Serializing a Value cannot fail.
        let mut text = serde_json::to_string_pretty(value).unwrap_or_default();
        text.push('\n');
        project.write_atomic(&dir.join(name), &text)?;
        files.push(format!("{INDEX_DIR}/{name}"));
    }
    project.write_atomic(&dir.join(".gitignore"), GITIGNORE)?;
    let count = |key: &str| {
        index
            .status
            .get(key)
            .and_then(Value::as_array)
            .map_or(0, std::vec::Vec::len)
    };
    Ok(Rebuilt {
        files,
        nodes: loaded.spec.nodes.len(),
        problems: count("problems"),
        broken_references: count("broken_references"),
    })
}

/// Keeps the generated folder out of the writer's git history.
const GITIGNORE: &str = "\
# Generated by Skaldsaga; rebuilt after every change. Not kept in history.
*
";

/// Builds the index for a loaded spec, without touching the disk.
pub fn build(loaded: &Loaded) -> Index {
    let spec = &loaded.spec;
    let registry = Registry::new(&spec.attributes);
    let lookup = Lookup::new(spec);
    let (backlinks, broken) = backlinks(spec, &lookup);
    let grid = grid(spec, &lookup);
    let totals = grid.totals;
    Index {
        backlinks: to_value(&backlinks),
        attributes: to_value(&attributes(spec, &registry)),
        grid: to_value(&grid),
        scenes: to_value(&scenes(spec, &lookup)),
        status: to_value(&status(loaded, totals, broken)),
    }
}

/// Every view is plain data with string keys, so serializing cannot fail.
fn to_value<T: Serialize>(view: &T) -> Value {
    serde_json::to_value(view).unwrap_or(Value::Null)
}

