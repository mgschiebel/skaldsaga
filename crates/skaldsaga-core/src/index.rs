#[derive(Debug, Clone, Copy, Default, Serialize)]
struct Labels {
    confirmed: usize,
    provisional: usize,
    unresolved: usize,
    unreviewed: usize,
    cleared: usize,
}

impl Labels {
    fn add(&mut self, confidence: Confidence, review: Review) {
        match confidence {
            Confidence::Confirmed => self.confirmed += 1,
            Confidence::Provisional => self.provisional += 1,
            Confidence::Unresolved => self.unresolved += 1,
        }
        match review {
            Review::Unreviewed => self.unreviewed += 1,
            Review::Cleared => self.cleared += 1,
        }
    }

    fn total(&self) -> usize {
        self.confirmed + self.provisional + self.unresolved
    }
}

#[derive(Debug, Clone, Copy, Default, Serialize)]
struct DecisionCounts {
    answered: usize,
    /// Answered with "keep it simple".
    kept_simple: usize,
    unanswered: usize,
}

#[derive(Serialize)]
struct NodeStatus<'a> {
    #[serde(rename = "type")]
    node_type: NodeType,
    name: &'a str,
    #[serde(skip_serializing_if = "Option::is_none")]
    summary: Option<&'a str>,
    /// Derived, never stored: for example "2 provisional, 1 unreviewed".
    status: String,
}

#[derive(Serialize)]
struct ProblemOut<'a> {
    path: &'a str,
    message: &'a str,
}

#[derive(Serialize)]
struct StatusOut<'a> {
    format: u32,
    built_by: String,
    counts: BTreeMap<&'static str, usize>,
    /// Labels across every fact and shape decision.
    labels: Labels,
    decisions: DecisionCounts,
    grid: CellCounts,
    nodes: IndexMap<&'a str, NodeStatus<'a>>,
    /// Files that couldn't be loaded, so they are missing from the index.
    problems: Vec<ProblemOut<'a>>,
    /// References to IDs that don't exist.
    broken_references: Vec<BrokenReference>,
}

/// The plain-language status line for one node.
fn node_status(labels: &Labels, unanswered: bool, kept_simple: bool) -> String {
    let mut parts = Vec::new();
    if unanswered {
        parts.push("unanswered".to_string());
    }
    if kept_simple {
        parts.push("kept simple".to_string());
    }
    for (n, word) in [
        (labels.unresolved, "unresolved"),
        (labels.provisional, "provisional"),
        (labels.unreviewed, "unreviewed"),
    ] {
        if n > 0 {
            parts.push(format!("{n} {word}"));
        }
    }
    if !parts.is_empty() {
        parts.join(", ")
    } else if labels.total() == 0 {
        "nothing to confirm yet".to_string()
    } else {
        "all confirmed and cleared".to_string()
    }
}

fn status<'a>(loaded: &'a Loaded, grid: CellCounts, broken: Vec<BrokenReference>) -> StatusOut<'a> {
    let spec = &loaded.spec;
    let mut counts: BTreeMap<&'static str, usize> =
        NodeType::ALL.iter().map(|t| (t.folder(), 0)).collect();
    let mut labels = Labels::default();
    let mut decisions = DecisionCounts::default();
    let mut nodes = IndexMap::new();
    let mut facts = 0;
    let mut scenes_outside = 0;
    let in_sequence: HashSet<&str> = spec.sequence.iter().map(String::as_str).collect();

    for node in &spec.nodes {
        *counts.entry(node.node_type().folder()).or_default() += 1;
        facts += node.facts.len();
        let mut own = Labels::default();
        for fact in &node.facts {
            own.add(fact.confidence, fact.review);
        }
        let (mut unanswered, mut kept_simple) = (false, false);
        match &node.body {
            NodeBody::Decision(d) => {
                own.add(d.confidence, d.review);
                match d.value.as_deref() {
                    None => {
                        unanswered = true;
                        decisions.unanswered += 1;
                    }
                    Some(NOT_EXPLORED) => {
                        kept_simple = true;
                        decisions.kept_simple += 1;
                    }
                    Some(_) => decisions.answered += 1,
                }
            }
            NodeBody::Scene(_) if !in_sequence.contains(node.id.as_str()) => scenes_outside += 1,
            _ => {}
        }
        labels.confirmed += own.confirmed;
        labels.provisional += own.provisional;
        labels.unresolved += own.unresolved;
        labels.unreviewed += own.unreviewed;
        labels.cleared += own.cleared;
        nodes.insert(
            node.id.as_str(),
            NodeStatus {
                node_type: node.node_type(),
                name: &node.name,
                summary: node.summary.as_deref(),
                status: node_status(&own, unanswered, kept_simple),
            },
        );
    }
    counts.insert("facts", facts);
    counts.insert(
        "scenes_in_sequence",
        counts
            .get(NodeType::Scene.folder())
            .copied()
            .unwrap_or(0)
            .saturating_sub(scenes_outside),
    );
    counts.insert("scenes_outside_sequence", scenes_outside);

    StatusOut {
        format: FORMAT,
        built_by: format!("skaldsaga {}", crate::VERSION),
        counts,
        labels,
        decisions,
        grid,
        nodes,
        problems: loaded
            .problems
            .iter()
            .map(|p| ProblemOut {
                path: &p.path,
                message: &p.message,
            })
            .collect(),
        broken_references: broken,
    }
}

