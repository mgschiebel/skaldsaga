#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize)]
struct Backlink {
    from: String,
    via: String,
}

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize)]
struct BrokenReference {
    from: String,
    via: String,
    target: String,
}

fn anchor_target(anchor: &TimeAnchor) -> Option<&str> {
    match anchor {
        TimeAnchor::After(a) => Some(&a.after),
        TimeAnchor::In(a) => Some(&a.scene),
        TimeAnchor::At(a) => Some(&a.at),
        TimeAnchor::Unknown(_) | TimeAnchor::Date(_) => None,
    }
}

/// Every stored reference in the spec, as (target, from, via).
pub(crate) fn references(spec: &Spec) -> Vec<(String, String, String)> {
    let mut out = Vec::new();
    for node in &spec.nodes {
        let from = node.id.as_str();
        let mut push = |target: &str, via: String| {
            // A node pointing at itself (a belief held by its own person)
            // tells no one anything.
            if target != from {
                out.push((target.to_string(), from.to_string(), via));
            }
        };
        match &node.body {
            NodeBody::Scene(s) => {
                if let Some(p) = &s.pov {
                    push(p, "pov".into());
                }
                if let Some(l) = &s.location {
                    push(l, "location".into());
                }
                for p in &s.participants {
                    push(p, "participants".into());
                }
                if let Some(c) = &s.coverage {
                    push(&c.thread, "coverage".into());
                }
                for f in &s.reads {
                    push(f, "reads".into());
                }
                if let Some(t) = s.when.as_ref().and_then(anchor_target) {
                    push(t, "when".into());
                }
            }
            NodeBody::Decision(d) => {
                for e in &d.evidence {
                    push(e, "evidence".into());
                }
                if let Some(p) = &d.pivot {
                    push(p, "pivot".into());
                }
            }
            NodeBody::Thread(t) => {
                push(&t.arc, "arc".into());
                for c in &t.characters {
                    push(&c.who, "characters".into());
                }
                for d in &t.decisions {
                    push(d, "decisions".into());
                }
            }
            NodeBody::Style(st) => {
                for v in &st.viewpoints {
                    push(&v.who, "viewpoints".into());
                }
            }
            NodeBody::Arc(a) => {
                for t in &a.threads {
                    push(t, "threads".into());
                }
                for d in &a.decisions {
                    push(d, "decisions".into());
                }
                for c in &a.characters {
                    push(c, "characters".into());
                }
                for (key, place) in &a.landmarks {
                    if let Some(p) = place {
                        push(&p.scene, format!("landmark:{key}"));
                    }
                }
                for (key, place) in &a.beats {
                    if let Some(p) = place {
                        push(&p.scene, format!("beat:{key}"));
                    }
                }
            }
            NodeBody::Person | NodeBody::Place | NodeBody::Group | NodeBody::Item => {}
        }

        for fact in &node.facts {
            let via = |field: &str| format!("fact:{}.{field}", fact.id);
            if let Some(v) = &fact.value
                && ids::kind_of(v).is_some()
            {
                push(v, via(fact.attribute.as_deref().unwrap_or("value")));
            }
            if let Some(h) = &fact.holder
                && ids::kind_of(h).is_some()
            {
                push(h, via("holder"));
            }
            if let Some(c) = &fact.contradicts {
                push(c, via("contradicts"));
            }
            if let Some(t) = fact.true_from.as_ref().and_then(anchor_target) {
                push(t, via("true_from"));
            }
            if let Some(t) = fact.ends.as_ref().and_then(anchor_target) {
                push(t, via("ends"));
            }
            if let Some(e) = &fact.ended_by {
                push(e, via("ended_by"));
            }
            for m in &fact.reader {
                let level = match m.level {
                    RevealLevel::Hinted => "reader.hinted",
                    RevealLevel::Revealed => "reader.revealed",
                };
                push(&m.scene, via(level));
            }
            for c in &fact.characters {
                push(&c.who, via("characters"));
                push(&c.learns_in, via("learns_in"));
            }
            for l in &fact.links {
                push(l, via("links"));
            }
        }
    }
    for id in &spec.sequence {
        out.push((
            id.clone(),
            SEQUENCE_FILE.to_string(),
            "sequence".to_string(),
        ));
    }
    out
}

/// The `from` used for references made by `sequence.md`.
pub const SEQUENCE_FROM: &str = SEQUENCE_FILE;

/// For every referenced ID, who references it and through which field
/// (the same data as `backlinks.json`, for in-memory use).
pub fn readers(spec: &Spec) -> HashMap<String, Vec<(String, String)>> {
    let mut out: HashMap<String, Vec<(String, String)>> = HashMap::new();
    for (target, from, via) in references(spec) {
        out.entry(target).or_default().push((from, via));
    }
    out
}

fn backlinks(
    spec: &Spec,
    lookup: &Lookup,
) -> (BTreeMap<String, Vec<Backlink>>, Vec<BrokenReference>) {
    let mut links: BTreeMap<String, Vec<Backlink>> = BTreeMap::new();
    let mut broken = Vec::new();
    for (target, from, via) in references(spec) {
        if lookup.exists(spec, &target) {
            links
                .entry(target)
                .or_default()
                .push(Backlink { from, via });
        } else {
            broken.push(BrokenReference { from, via, target });
        }
    }
    for list in links.values_mut() {
        list.sort();
        list.dedup();
    }
    broken.sort();
    broken.dedup();
    (links, broken)
}

