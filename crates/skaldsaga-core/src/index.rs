#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub(crate) enum Method {
    /// Boundaries come from the arc's landmark scenes.
    Landmarks,
    /// Not every boundary landmark is usable yet, so each scene falls back
    /// on the stage in its `coverage` field.
    Coverage,
}

#[derive(Default, Serialize)]
pub(crate) struct Movements {
    pub(crate) setup: Vec<String>,
    pub(crate) complications: Vec<String>,
    pub(crate) crisis: Vec<String>,
    pub(crate) resolution: Vec<String>,
    /// Scenes in the arc's span that no movement could be found for.
    pub(crate) unplaced: Vec<String>,
}

impl Movements {
    /// The scenes of one movement, in reading order.
    pub(crate) fn stage(&self, stage: Stage) -> &[String] {
        match stage {
            Stage::Setup => &self.setup,
            Stage::Complications => &self.complications,
            Stage::Crisis => &self.crisis,
            Stage::Resolution => &self.resolution,
        }
    }

    fn stage_mut(&mut self, stage: Stage) -> &mut Vec<String> {
        match stage {
            Stage::Setup => &mut self.setup,
            Stage::Complications => &mut self.complications,
            Stage::Crisis => &mut self.crisis,
            Stage::Resolution => &mut self.resolution,
        }
    }
}

#[derive(Serialize)]
pub(crate) struct ArcMovements {
    pub(crate) method: Method,
    /// Why the landmarks couldn't be used, when some are placed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) note: Option<String>,
    #[serde(flatten)]
    pub(crate) movements: Movements,
}

/// Each arc's movements as the index derives them (the main story and active
/// subplots), for the checks in `complete`.
pub(crate) fn derived_movements(spec: &Spec) -> BTreeMap<String, ArcMovements> {
    let lookup = Lookup::new(spec);
    let order = reading_order(spec);
    movements(spec, &lookup, &order)
}

/// Scene IDs in reading order, leaving out any that don't exist as scenes.
pub(crate) fn reading_order(spec: &Spec) -> Vec<String> {
    spec.sequence
        .iter()
        .filter(|id| matches!(spec.node(id).map(|n| &n.body), Some(NodeBody::Scene(_))))
        .cloned()
        .collect()
}

/// Thread ID to the arc it belongs to, from the thread's own `arc` field or
/// the arc's `threads` list.
pub(crate) fn thread_arcs(spec: &Spec) -> HashMap<String, String> {
    Lookup::new(spec)
        .thread_arc
        .into_iter()
        .map(|(t, a)| (t.to_string(), a.to_string()))
        .collect()
}

#[derive(Serialize)]
struct ScenesOut<'a> {
    /// Scene IDs in reading order.
    order: Vec<String>,
    /// Alternative scenes, not in the reading order.
    outside_sequence: Vec<String>,
    /// Every scene, in reading order, then the alternatives.
    scenes: IndexMap<String, SceneOut<'a>>,
    /// Per arc (the main story and active subplots): its scenes split into
    /// the four movements. Derived on every rebuild, never stored.
    movements: BTreeMap<String, ArcMovements>,
}

fn scenes<'a>(spec: &'a Spec, lookup: &Lookup) -> ScenesOut<'a> {
    let mut out: IndexMap<String, SceneOut<'a>> = IndexMap::new();
    let mut ids: Vec<&str> = scene_nodes(spec).map(|(n, _)| n.id.as_str()).collect();
    ids.sort_by_key(|id| lookup.order_key(id));
    for id in &ids {
        let Some(node) = spec.node(id) else { continue };
        let NodeBody::Scene(s) = &node.body else {
            continue;
        };
        out.insert(
            node.id.clone(),
            SceneOut {
                name: &node.name,
                summary: node.summary.as_deref(),
                status: s.status,
                in_sequence: lookup.position.contains_key(id),
                purpose: s.purpose.as_deref(),
                pov: s.pov.as_deref(),
                location: s.location.as_deref(),
                participants: &s.participants,
                coverage: s.coverage.as_ref(),
                reads: &s.reads,
                writes: Vec::new(),
                ends: Vec::new(),
                hints: Vec::new(),
                reveals: Vec::new(),
                learns: Vec::new(),
                landmarks: Vec::new(),
                beats: Vec::new(),
                movements: Vec::new(),
            },
        );
    }

    // What the facts say happens in each scene.
    let in_scene = |a: &Option<TimeAnchor>| match a {
        Some(TimeAnchor::In(i)) => Some(i.scene.clone()),
        _ => None,
    };
    for node in &spec.nodes {
        for fact in &node.facts {
            if let Some(scene) = in_scene(&fact.true_from)
                && let Some(s) = out.get_mut(&scene)
            {
                s.writes.push(fact.id.clone());
            }
            if let Some(scene) = in_scene(&fact.ends)
                && let Some(s) = out.get_mut(&scene)
            {
                s.ends.push(fact.id.clone());
            }
            for m in &fact.reader {
                if let Some(s) = out.get_mut(&m.scene) {
                    match m.level {
                        RevealLevel::Hinted => s.hints.push(fact.id.clone()),
                        RevealLevel::Revealed => s.reveals.push(fact.id.clone()),
                    }
                }
            }
            for c in &fact.characters {
                if let Some(s) = out.get_mut(&c.learns_in) {
                    s.learns.push(Learn {
                        fact: fact.id.clone(),
                        who: c.who.clone(),
                        how: c.how,
                    });
                }
            }
        }
        if let NodeBody::Arc(arc) = &node.body {
            for (maps, beat) in [(&arc.landmarks, false), (&arc.beats, true)] {
                for (key, place) in maps {
                    let Some(place) = place else { continue };
                    if let Some(s) = out.get_mut(&place.scene) {
                        let p = Placement {
                            arc: node.id.clone(),
                            key: key.clone(),
                            confidence: place.confidence,
                        };
                        if beat {
                            s.beats.push(p);
                        } else {
                            s.landmarks.push(p);
                        }
                    }
                }
            }
        }
    }
    for s in out.values_mut() {
        s.writes.sort();
        s.ends.sort();
        s.hints.sort();
        s.reveals.sort();
        s.learns
            .sort_by(|a, b| (&a.fact, &a.who).cmp(&(&b.fact, &b.who)));
        s.landmarks
            .sort_by(|a, b| (&a.arc, &a.key).cmp(&(&b.arc, &b.key)));
        s.beats
            .sort_by(|a, b| (&a.arc, &a.key).cmp(&(&b.arc, &b.key)));
    }

    let order: Vec<String> = spec
        .sequence
        .iter()
        .filter(|id| out.contains_key(*id))
        .cloned()
        .collect();
    let outside_sequence = ids
        .iter()
        .filter(|id| !lookup.position.contains_key(*id))
        .map(|id| id.to_string())
        .collect();

    let movements = movements(spec, lookup, &order);
    for (arc, m) in &movements {
        for stage in Stage::ALL {
            let list = match stage {
                Stage::Setup => &m.movements.setup,
                Stage::Complications => &m.movements.complications,
                Stage::Crisis => &m.movements.crisis,
                Stage::Resolution => &m.movements.resolution,
            };
            for id in list {
                if let Some(s) = out.get_mut(id) {
                    s.movements.push(InMovement {
                        arc: arc.clone(),
                        stage,
                    });
                }
            }
        }
    }

    ScenesOut {
        order,
        outside_sequence,
        scenes: out,
        movements,
    }
}

/// Splits each arc's scenes into the four movements (HANDOFF, Coverage grid
/// and movements). The end of Setup is the scene where the MC commits, the
/// end of Complications the midpoint, the end of Crisis the low point, and
/// Resolution is everything after. Until all three are placed in order, each
/// scene falls back on its `coverage` stage.
///
/// The main story spans the whole reading order; a subplot spans from its
/// first scene to its last (scenes covering its threads, or placed as its
/// landmarks or beats).
fn movements(spec: &Spec, lookup: &Lookup, order: &[String]) -> BTreeMap<String, ArcMovements> {
    let mut out = BTreeMap::new();
    for node in &spec.nodes {
        let NodeBody::Arc(arc) = &node.body else {
            continue;
        };
        if !matches!(arc.status, ArcStatus::Main | ArcStatus::Active) {
            continue;
        }
        let arc_of_scene = |id: &str| -> Option<Stage> {
            let Some(NodeBody::Scene(s)) = spec.node(id).map(|n| &n.body) else {
                return None;
            };
            let c = s.coverage.as_ref()?;
            (lookup.thread_arc.get(c.thread.as_str()) == Some(&node.id.as_str())).then_some(c.stage)
        };
        let placed: HashSet<&str> = arc
            .landmarks
            .values()
            .chain(arc.beats.values())
            .flatten()
            .map(|p| p.scene.as_str())
            .collect();

        let span: &[String] = if arc.status == ArcStatus::Main {
            order
        } else {
            let mine: Vec<usize> = order
                .iter()
                .enumerate()
                .filter(|(_, id)| arc_of_scene(id).is_some() || placed.contains(id.as_str()))
                .map(|(i, _)| i)
                .collect();
            match (mine.first(), mine.last()) {
                (Some(&a), Some(&b)) => order.get(a..=b).unwrap_or(&[]),
                _ => &[],
            }
        };

        // Boundary positions within the span, if all three are usable.
        let boundary = |key: &str| -> Result<usize, Option<String>> {
            let place = arc
                .landmarks
                .get(key)
                .and_then(Option::as_ref)
                .ok_or(None)?;
            span.iter()
                .position(|id| *id == place.scene)
                .ok_or_else(|| {
                    Some(format!(
                        "the '{key}' landmark scene isn't in this story's reading order"
                    ))
                })
        };
        let mut note = None;
        let mut bounds = Vec::new();
        for key in MOVEMENT_BOUNDARIES {
            match boundary(key) {
                Ok(p) => bounds.push(p),
                Err(n) => {
                    note = note.or(n);
                }
            }
        }
        // The three boundaries, in story order, when all are usable.
        let ordered = match *bounds.as_slice() {
            [a, b, c] if bounds.len() == MOVEMENT_BOUNDARIES.len() && a < b && b < c => {
                Some((a, b, c))
            }
            _ => None,
        };
        let usable = ordered.is_some();
        if bounds.len() == MOVEMENT_BOUNDARIES.len() && !usable {
            note = Some("the landmarks that end the movements are out of order".to_string());
        }

        let mut m = Movements::default();
        let method = if let Some((first, second, third)) = ordered {
            for (i, id) in span.iter().enumerate() {
                let stage = if i <= first {
                    Stage::Setup
                } else if i <= second {
                    Stage::Complications
                } else if i <= third {
                    Stage::Crisis
                } else {
                    Stage::Resolution
                };
                m.stage_mut(stage).push(id.clone());
            }
            Method::Landmarks
        } else {
            for id in span {
                match arc_of_scene(id) {
                    Some(stage) => m.stage_mut(stage).push(id.clone()),
                    None => m.unplaced.push(id.clone()),
                }
            }
            Method::Coverage
        };
        out.insert(
            node.id.clone(),
            ArcMovements {
                method,
                note,
                movements: m,
            },
        );
    }
    out
}

